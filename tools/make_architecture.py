def signature(fn: ast.FunctionDef) -> str:
    """Render a def's arguments the way the source writes them."""
    a = fn.args
    out = []
    positional = a.posonlyargs + a.args
    # ast stores defaults right-aligned against the positional args, so pad
    # the left with None to get them to line up with their own parameter.
    defaults = [None] * (len(positional) - len(a.defaults)) + list(a.defaults)
    for arg, default in zip(positional, defaults):
        out.append(arg.arg if default is None
                   else f"{arg.arg}={ast.unparse(default)}")
    if a.vararg:
        out.append("*" + a.vararg.arg)
    elif a.kwonlyargs:
        out.append("*")              # bare star: keyword-only follow
    for arg, default in zip(a.kwonlyargs, a.kw_defaults):
        out.append(arg.arg if default is None
                   else f"{arg.arg}={ast.unparse(default)}")
    if a.kwarg:
        out.append("**" + a.kwarg.arg)
    return "(" + ", ".join(out) + ")"


def summary(node) -> str:
    """First line of the docstring, which is where the point always is."""
    doc = ast.get_docstring(node)
    return doc.strip().split("\n")[0] if doc else ""


def clip(text: str, n: int) -> str:
    return text if len(text) <= n else text[:n - 3] + "..."


def api(path: pathlib.Path) -> dict:
    """Every public name a module defines, with its signature."""
    tree = ast.parse(path.read_text())
    out = {"doc": summary(tree), "consts": [], "items": []}
    for node in tree.body:
        # Module-level SHOUTING names are the tuning knobs; they matter as
        # much as the functions and are easy to lose.
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id.isupper():
                    out["consts"].append(
                        f"{t.id} = {clip(ast.unparse(node.value), 44)}")
        elif isinstance(node, ast.FunctionDef):
            out["items"].append(
                ("def", node.name + signature(node), summary(node), []))
        elif isinstance(node, ast.ClassDef):
            decorators = [ast.unparse(d).split("(")[0]
                          for d in node.decorator_list]
            label = node.name
            if node.bases:
                label += "(" + ", ".join(ast.unparse(b)
                                         for b in node.bases) + ")"
            if decorators:
                label = "@" + " @".join(decorators) + " " + label
            members = []
            for m in node.body:
                if isinstance(m, ast.FunctionDef):
                    md = [ast.unparse(d).split("(")[0]
                          for d in m.decorator_list]
                    prefix = f"@{md[0]} " if md else ""
                    members.append((prefix + m.name + signature(m),
                                    summary(m)))
                # Dataclass fields are the shape of the object and belong
                # in the map as much as its methods do.
                elif isinstance(m, ast.AnnAssign) and \
                        isinstance(m.target, ast.Name):
                    field = f"{m.target.id}: {ast.unparse(m.annotation)}"
                    if m.value is not None:
                        field += " = " + clip(ast.unparse(m.value), 30)
                    members.append((field, ""))
            out["items"].append(("class", label, summary(node), members))
    return out


def walk(base: pathlib.Path):
    """Directories depth-first, each with its files, both sorted."""
    dirs = [base] + sorted(d for d in base.rglob("*")
                           if d.is_dir() and not
                           any(s in d.parts for s in SKIP_DIRS))
    for d in dirs:
        files = sorted(f for f in d.iterdir()
                       if f.is_file() and f.name not in SKIP_FILES
                       and f.suffix not in SKIP_SUFFIX)
        if files:
            yield d, files


def one_liner(path: pathlib.Path) -> str:
    """A few words on what a file is, for the tree at the top."""
    if path.suffix == ".py" and not \
            path.relative_to(ROOT).as_posix().startswith(NO_PARSE):
        try:
            return clip(summary(ast.parse(path.read_text())), 70)
        except SyntaxError:
            return ""
    kb = path.stat().st_size / 1024
    return f"{kb:,.0f} kB" if kb >= 1 else f"{path.stat().st_size} B"


def tree(base: pathlib.Path, prefix: str = "") -> list[str]:
    """The classic box-drawing tree, files annotated.

    Directories first, then files, each sorted -- so the shape of the
    package reads before its contents do.
    """
    kids = [c for c in sorted(base.iterdir(),
                              key=lambda c: (c.is_file(), c.name))
            if c.name not in SKIP_FILES and c.suffix not in SKIP_SUFFIX
            and c.name not in SKIP_DIRS]
    out = []
    for i, c in enumerate(kids):
        last = i == len(kids) - 1
        stem = "`-- " if last else "|-- "
        if c.is_dir():
            out.append(f"{prefix}{stem}{c.name}/")
            out += tree(c, prefix + ("    " if last else "|   "))
        else:
            note = one_liner(c)
            label = f"{prefix}{stem}{c.name}"
            out.append(f"{label:<46}{('  ' + note) if note else ''}".rstrip())
    return out


def registry() -> list[str]:
    """Layouts and cases as they actually register at import.

    Read by importing rather than by parsing, because a layout is built by
    running code -- the wiring is not visible in the syntax tree.  If this
    section is missing from the output, the package did not import, which
    is itself worth knowing.
    """
    try:
        from project.cases import CASES
        from brayton_cycle import LAYOUTS
    except Exception as e:                       # noqa: BLE001
        return ["## Registered layouts and cases", "",
                f"*(could not import: {type(e).__name__}: {e})*", ""]

    out = ["## Registered layouts", "",
           "Block id and type, in topological order. This is the whole of",
           "what a layout file contains -- no numbers.", "", "```text"]
    for name, lay in LAYOUTS.items():
        chain = "  ".join(f"{n.id}[{n.type}]" for n in lay.nodes)
        out.append(f"{name:<16} {chain}")
    out += ["```", "",
            f"## Registered cases ({len(CASES)})", "",
            "Importable by name from `project.cases`. Note that",
            "`air_brayton_real` means real *machines* (eta < 1), not a",
            "real fluid -- hence the ideal-gas backend.", "",
            "```text",
            f"{'case':<28} {'layout':<16} {'fluid':<10} backend"]
    for name, case in CASES.items():
        out.append(f"{name:<28} {case.layout.name:<16} "
                   f"{case.fluid:<10} {case.backend}")
    out += ["```", ""]
    return out


def render() -> str:
    lines = [
        "# Architecture",
        "",
        "**Generated** by `python -m tools.make_architecture`.",
        "Do not edit by hand -- regenerate it. Every signature, constant",
        "and docstring line below is read out of the source, so this file",
        "is wrong only if the source changed and nobody re-ran the script.",
        "",
        "The directory notes are the one hand-written part, and they live",
        "in `PURPOSE` at the top of that script.",
        "",
        "---",
        "",
        "## The tree",
        "",
        "```text",
        "Programming/",
    ]
    for top in TREE:
        base = ROOT / top
        if base.exists():
            lines.append(f"|-- {top}/")
            lines += tree(base, "|   ")
    lines += ["```", ""]
    lines += registry()
    lines += ["Everything below is the same tree with each module's API",
              "spelled out.", ""]
    for top in TREE:
        base = ROOT / top
        if not base.exists():
            continue
        for d, files in walk(base):
            rel = d.relative_to(ROOT).as_posix()
            lines += ["", f"## `{rel}/`"]
            if rel in PURPOSE:
                lines += ["", PURPOSE[rel]]
            lines.append("")
            for f in files:
                frel = f.relative_to(ROOT).as_posix()
                if f.suffix != ".py" or rel.startswith(NO_PARSE):
                    lines.append(f"- **`{f.name}`** &mdash; "
                                 f"{f.stat().st_size:,} bytes")
                    continue
                n = len(f.read_text().splitlines())
                try:
                    info = api(f)
                except SyntaxError as e:
                    # Say so rather than dying: one unparseable file must
                    # not cost the whole map.
                    lines += ["", f"### `{f.name}` ({n} lines)", "",
                              f"- *(does not parse: {e.msg} at line "
                              f"{e.lineno})*"]
                    continue
                head = f"### `{f.name}` ({n} lines)"
                lines += ["", head, ""]
                if info["doc"]:
                    lines += [f"> {info['doc']}", ""]
                for c in info["consts"]:
                    lines.append(f"- `{c}`")
                if info["consts"] and info["items"]:
                    lines.append("")
                for kind, label, doc, members in info["items"]:
                    tail = f" &mdash; {doc}" if doc else ""
                    lines.append(f"- `{label}`{tail}")
                    for m, md in members:
                        mt = f" &mdash; {md}" if md else ""
                        lines.append(f"  - `{m}`{mt}")
                if not info["consts"] and not info["items"]:
                    lines.append("- *(no module-level definitions)*")
    return "\n".join(lines) + "\n"


def main():
    OUT.write_text(render())
    print(f"written: {OUT}  ({len(OUT.read_text().splitlines())} lines)")


if __name__ == "__main__":
    main()
